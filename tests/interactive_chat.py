import os
import sys
# Automatically add project root to Python path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from dotenv import load_dotenv
from src.agent import graph, store

load_dotenv(".env")

def run_interactive_chat():
    print("\n========================================")
    print("💬 INTERACTIVE AGENT CHAT & PGVECTOR CLI")
    print("========================================")
    print("Type your message and press Enter to chat.")
    print("Just press Enter on an empty line to EXIT.\n")

    user_id = "sergio_user"
    thread_id = "interactive_thread_01"
    namespace = ("users", user_id)
    # "confifurable" comes from the LangGraph framework, allowing dynamic configuration of the agent's behavior based on user and thread context. It enables the agent to maintain state and memory across different sessions and users.
    config = {"configurable": {"thread_id": thread_id, "user_id": user_id}}

    while True:
        try:
            user_input = input("User > ").strip()
            
            # If user presses Enter without typing, exit the loop
            if not user_input:
                print("\n[Exit] Empty input received. Closing chat and saving session state.")
                break
            
            # 1. Invoke the agent graph (uses checkpointer for short-term history & pgvector for long-term memory search)
            message = {"messages": [("user", user_input)]}
            response = graph.invoke(message, config=config)
            agent_reply = response["messages"][-1].content
            
            print(f"\nAgent > {agent_reply}\n")
            
            # 2. Save the user message and agent response to the pgvector long-term store
            # The memory_key is generated by hashing the user input to create a unique identifier for each interaction. This ensures that even if the same question is asked multiple times, each interaction is stored separately in the long-term memory store. The store.put method saves both the user's question and the agent's response under this unique key, allowing for future retrieval and context-aware responses.
            memory_key = f"interaction_{abs(hash(user_input)) % 100000}"
            store.put(
                namespace,
                memory_key,
                {"text": f"User asked: '{user_input}' | Agent answered: '{agent_reply}'"}
            )
            print("💾 [Saved to pgvector long-term memory store]\n")
            print("-" * 45)

        except (KeyboardInterrupt, EOFError):
            print("\n[Exit] Session terminated by user.")
            break

    print("\n========================================")
    print("✨ INTERACTIVE SESSION COMPLETED")
    print("========================================")

if __name__ == "__main__":
    run_interactive_chat()